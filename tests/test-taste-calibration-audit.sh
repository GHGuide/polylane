  bind_panel "$d" a
  assert_cfg_code "$d" HUMAN_CLAIM hclaim
  jq -e '.panel.reason_codes | index("HUMAN_CLAIM") != null' "$d/out.json" >/dev/null \
    || fail 'hclaim: human-claim escalation poisons the panel'
  test "$(jq -r '.human_certified' "$d/out.json")" = false || fail 'hclaim: audit stays human_certified:false'
}
