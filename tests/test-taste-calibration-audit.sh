test_stale_config_receipt() {
  local d; d=$(mk stale); build_config "$d" a 17
  edit_json "$d/a/receipt.json" '.judge_configuration.system_prompt_sha256 = "'"$(rep64 9)"'"'
  bind_panel "$d" a
  assert_cfg_code "$d" STALE_CONFIG stale
}
test_changed_holdout_after_receipt() {
  local d; d=$(mk holdout); build_config "$d" a 17; bind_panel "$d" a
  edit_json "$d/a/labels.json" '.labels[0].correct_stimulus = .labels[0].stimulus_ids[1]'
  assert_cfg_code "$d" HOLDOUT_BINDING holdout
