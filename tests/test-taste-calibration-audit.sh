test_receipt_numbers_tampered() {
  local d; d=$(mk rnum); build_config "$d" a 17
  edit_json "$d/a/receipt.json" '.correct_units = 24 | .correct = 24 | .accuracy = 1'
  bind_panel "$d" a
  assert_cfg_code "$d" RECEIPT_MISMATCH rnum
}
test_human_claim_escalation_rejected() {
  local d; d=$(mk hclaim); build_config "$d" a 17
