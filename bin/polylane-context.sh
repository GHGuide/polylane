#!/usr/bin/env bash
# polylane-context.sh — deterministic, bounded context packets from durable state.
#
# Usage:
#   polylane-context.sh refresh <project-root> [--worker <id>]
#   polylane-context.sh packet <project-root> <packet-dir> <byte-budget> <query> \
#     [--goal <locked-goal>] [--subgoal <current-subgoal>] [--worker <id>]
#   polylane-context.sh query ... # alias for packet
#
# The allowlist is intentionally closed: durable documents below docs/polylane,
# bounded max-state data, decision records, corpus/recent digests, harness records,
# and one named worker's capsule and pending inbox.  It never reads arbitrary paths.

set -euo pipefail

# These caps are source-discovery limits, independent of the caller's packet
# byte budget.  They keep a long-lived project from turning a pre-launch query
# into an ever-growing scan or prompt.
MAX_DECISIONS=24
MAX_HARNESS_ENTRIES=24
MAX_RECENT_CYCLE_FILES=12
MAX_INBOX_MESSAGES=24
MAX_STATE_BRIEF_BYTES=4096

usage() {
  echo "usage: polylane-context.sh refresh <project-root> [--worker <id>] | packet <project-root> <packet-dir> <byte-budget> <query> [--goal <locked-goal>] [--subgoal <current-subgoal>] [--worker <id>]" >&2
  exit 2
}

die() { echo "context: $*" >&2; exit 2; }

bytes() { wc -c < "$1" | tr -d ' '; }

secret_like() {
  case "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" in
    *secret*|*token*|*password*|*credential*|*private*|*.pem|*.key|*.env) return 0 ;;
    *) return 1 ;;
  esac
}

canonical_root() {
  local supplied="$1" root
  [ -n "$supplied" ] || die "project root is required"
  root=$(cd "$supplied" 2>/dev/null && pwd -P) || die "unsafe project root: $supplied"
  [ "$root" != "/" ] || die "unsafe project root: /"
  [ -d "$root/docs/polylane" ] || die "unsafe project root (missing docs/polylane): $root"
  printf '%s\n' "$root"
}

valid_worker() {
  local worker="$1"
  case "$worker" in
    ''|*[!A-Za-z0-9_-]*) return 1 ;;
  esac
  secret_like "$worker" && return 1
  return 0
}

# add_source REL LABEL RECENCY FILE.  The global source list uses only paths
# generated by collect_sources, never caller-controlled source paths.
add_source() {
  local rel="$1" label="$2" recency="$3" file="$4"
  if secret_like "$(basename "$rel")"; then
    die "secret-like source rejected: $rel"
  elif [ -f "$file" ]; then
    printf '%s\t%s\t%s\t%s\n' "$rel" "$label" "$recency" "$file" >> "$SOURCES"
  else
    printf '%s\n' "$rel" >> "$MISSING"
  fi
}

add_recent_cycle_files() {
  local directory="$1" file rel base_name cycle cycle_number n=0 total=0
  [ -d "$directory" ] || return 0

  # Prefix each path with its numeric cycle.  A separate sortable key avoids
  # treating cycle-9 as newer than cycle-12 and makes the selection stable.
  while IFS= read -r file; do
    base_name=$(basename "$file")
    cycle=${base_name#cycle-}
    cycle=${cycle%%-*}
    case "$cycle" in ''|*[!0-9]*) continue ;; esac
    cycle_number=$((10#$cycle))
    printf '%010d\t%s\n' "$cycle_number" "$file"
  done < <(find "$directory" -maxdepth 1 -type f -name 'cycle-[0-9]*-*.md' -print 2>/dev/null) |
    LC_ALL=C sort -t "$(printf '\t')" -k1,1nr -k2,2 > "$RECENT_LIST"

  while IFS="$(printf '\t')" read -r cycle file; do
    total=$((total + 1))
    if [ "$n" -ge "$MAX_RECENT_CYCLE_FILES" ]; then
      continue
    fi
    rel="${file#"$ROOT"/}"
    cycle_number=$((10#$cycle))
    add_source "$rel" 'recent cycle material' "$((600 + cycle_number))" "$file"
    n=$((n + 1))
  done < "$RECENT_LIST"
  if [ "$total" -gt "$MAX_RECENT_CYCLE_FILES" ]; then
    printf 'docs/polylane/cycle-*-*.md (source limit: %s)\n' "$MAX_RECENT_CYCLE_FILES" >> "$OMITTED"
  fi
}

write_max_brief() {
  local state="$ROOT/docs/polylane/max-state.json"
  [ -f "$state" ] || { printf '%s\n' 'docs/polylane/max-state.json' >> "$MISSING"; return; }
  if ! jq -e . "$state" >/dev/null 2>&1; then
    printf '%s\n' 'docs/polylane/max-state.json (invalid JSON)' >> "$OMITTED"
    return
  fi
  # This is a fixed, bounded projection rather than an injection of full state.
  jq -r '
    "ULTIMATE: " + (.ultimate // "(unknown)"),
    "OPEN CRITERIA:",
    (.criteria // [] | map(select(.status != "done") | ((.id // "criterion") + ": " + (.text // ""))) | .[:12][]?),
    "RECENT LOG:",
    (.log // [] | sort_by(.cycle // 0) | reverse | .[:8][]? |
      ("cycle " + ((.cycle // 0) | tostring) + " " + (.kind // "entry") + ": " + (.text // "")))
  ' "$state" | dd bs="$MAX_STATE_BRIEF_BYTES" count=1 2>/dev/null > "$MAX_BRIEF"
  add_source 'docs/polylane/max-state.json' 'bounded max-state brief' 900 "$MAX_BRIEF"
}

prepare_pending_inbox() {
  local inbox="$1" kept total
  [ -f "$inbox" ] || return 1
  if ! jq -c 'select((.acknowledged // false) != true)' "$inbox" > "$PENDING_INBOX" 2>/dev/null; then
    printf 'docs/polylane/workers/%s/inbox.jsonl (invalid JSONL)\n' "$WORKER" >> "$OMITTED"
    return 1
  fi
  total=$(wc -l < "$PENDING_INBOX" | tr -d ' ')
  if [ "$total" -gt "$MAX_INBOX_MESSAGES" ]; then
    kept="$TMPDIR_CONTEXT/pending-inbox-bounded.jsonl"
    sed -n "1,${MAX_INBOX_MESSAGES}p" "$PENDING_INBOX" > "$kept"
    mv "$kept" "$PENDING_INBOX"
    printf 'docs/polylane/workers/%s/inbox.jsonl (message limit: %s)\n' "$WORKER" "$MAX_INBOX_MESSAGES" >> "$OMITTED"
  fi
  return 0
}

collect_sources() {
  local base="$ROOT/docs/polylane" file rel n total
  : > "$SOURCES"; : > "$MISSING"; : > "$OMITTED"
  add_source 'docs/polylane/NORTHSTAR.md' 'north star' 1000 "$base/NORTHSTAR.md"
  add_source 'docs/polylane/STRATEGY.md' 'strategy' 990 "$base/STRATEGY.md"
  add_source 'docs/polylane/ULTIMATE_GOAL.md' 'ultimate goal' 980 "$base/ULTIMATE_GOAL.md"
  write_max_brief
  add_source 'docs/polylane/decisions/INDEX.md' 'decision index' 800 "$base/decisions/INDEX.md"
  if [ -d "$base/decisions" ]; then
    n=0; total=0
    while IFS= read -r file; do
      total=$((total + 1))
      rel="${file#"$ROOT"/}"
      [ "$rel" = 'docs/polylane/decisions/INDEX.md' ] && continue
      if [ "$n" -ge "$MAX_DECISIONS" ]; then continue; fi
      add_source "$rel" 'decision record' 790 "$file"
      n=$((n + 1))
    done < <(find "$base/decisions" -maxdepth 1 -type f -name '[0-9][0-9][0-9]-*.md' -print 2>/dev/null | LC_ALL=C sort)
    if [ "$total" -gt "$MAX_DECISIONS" ]; then
      printf 'docs/polylane/decisions/ (source limit: %s)\n' "$MAX_DECISIONS" >> "$OMITTED"
    fi
  fi
  add_source 'docs/polylane/corpus.md' 'continuity corpus' 700 "$base/corpus.md"
  add_recent_cycle_files "$base"
  if [ -d "$base/harness" ]; then
    n=0; total=0
    while IFS= read -r file; do
      total=$((total + 1))
      if [ "$n" -ge "$MAX_HARNESS_ENTRIES" ]; then continue; fi
      rel="${file#"$ROOT"/}"
      add_source "$rel" 'continual harness entry' 650 "$file"
      n=$((n + 1))
    done < <(find "$base/harness" -maxdepth 1 -type f \( -name '*.md' -o -name '*.json' \) -print 2>/dev/null | LC_ALL=C sort)
    if [ "$total" -gt "$MAX_HARNESS_ENTRIES" ]; then
      printf 'docs/polylane/harness/ (source limit: %s)\n' "$MAX_HARNESS_ENTRIES" >> "$OMITTED"
    fi
  else
    printf '%s\n' 'docs/polylane/harness/' >> "$MISSING"
  fi
  if [ -n "$WORKER" ]; then
    add_source "docs/polylane/workers/$WORKER/capsule.md" 'worker capsule' 950 "$base/workers/$WORKER/capsule.md"
    add_source "docs/polylane/workers/$WORKER/capsule.json" 'worker capsule' 950 "$base/workers/$WORKER/capsule.json"
    add_source "docs/polylane/workers/$WORKER/inbox.md" 'pending worker inbox' 940 "$base/workers/$WORKER/inbox.md"
    if prepare_pending_inbox "$base/workers/$WORKER/inbox.jsonl"; then
      add_source "docs/polylane/workers/$WORKER/inbox.jsonl" 'pending worker inbox' 940 "$PENDING_INBOX"
    else
      [ -f "$base/workers/$WORKER/inbox.jsonl" ] ||
        printf 'docs/polylane/workers/%s/inbox.jsonl\n' "$WORKER" >> "$MISSING"
    fi
  fi
}

make_candidates() {
  local rel label recency file terms
  terms=$(printf '%s' "$QUERY" | tr '[:upper:]' '[:lower:]' | tr -cs '[:alnum:]_' ' ')
  while IFS="$(printf '\t')" read -r rel label recency file; do
    awk -v rel="$rel" -v label="$label" -v recency="$recency" -v terms="$terms" '
      BEGIN { count=split(terms, term, " "); section="document" }
      /^#[#]*[[:space:]]/ { section=$0; sub(/^#+[[:space:]]*/, "", section); next }
      /^[[:space:]]*$/ { next }
      {
        lower=tolower($0); score=0
        for (i=1; i<=count; i++) if (term[i] != "" && index(lower, term[i])) score++
        printf "%06d\t%010d\t%s\t%s\t%06d\t%s\n", score, recency, rel, section, NR, $0
      }
    ' "$file"
  done < "$SOURCES" | LC_ALL=C sort -t "$(printf '\t')" -k1,1nr -k2,2nr -k3,3 -k5,5n > "$CANDIDATES"
}

append_unique() {
  local list="$1" value="$2"
  grep -qxF -- "$value" "$list" 2>/dev/null || printf '%s\n' "$value" >> "$list"
}

render_packet() {
  local rel section lineno content snippet current
  printf '# Polylane context packet\n\n' > "$PACKET_TMP"
  if [ -n "$GOAL" ]; then printf '## Locked goal\n%s\n\n' "$GOAL" >> "$PACKET_TMP"; fi
  if [ -n "$SUBGOAL" ]; then printf '## Current subgoal\n%s\n\n' "$SUBGOAL" >> "$PACKET_TMP"; fi
  printf '## Ranked context\n\n' >> "$PACKET_TMP"
  [ "$(bytes "$PACKET_TMP")" -le "$BUDGET" ] || die "locked goal/current subgoal exceed byte budget"
  : > "$USED"; : > "$TRUNCATED"
  while IFS="$(printf '\t')" read -r _score _recency rel section lineno content; do
    snippet=$(mktemp "$TMPDIR_CONTEXT/snippet.XXXXXX")
    printf '### Source: %s\nSection: %s (line %s)\n%s\n\n' "$rel" "$section" "$lineno" "$content" > "$snippet"
    current=$(( $(bytes "$PACKET_TMP") + $(bytes "$snippet") ))
    if [ "$current" -le "$BUDGET" ]; then
      cat "$snippet" >> "$PACKET_TMP"
      append_unique "$USED" "$rel"
    else
      append_unique "$TRUNCATED" "$rel"
    fi
    rm -f "$snippet"
  done < "$CANDIDATES"
}

json_array() {
  local list="$1"
  if [ -s "$list" ]; then jq -Rsc 'split("\n") | map(select(length > 0))' "$list"; else printf '[]'; fi
}

write_manifest() {
  local count checksum used missing omitted truncated
  count=$(bytes "$PACKET_TMP")
  checksum=$(cksum "$PACKET_TMP" | awk '{print "cksum:" $1 ":" $2}')
  used=$(json_array "$USED"); missing=$(json_array "$MISSING")
  omitted=$(json_array "$OMITTED"); truncated=$(json_array "$TRUNCATED")
  jq -n --arg query "$QUERY" --arg checksum "$checksum" --argjson byte_count "$count" \
    --argjson used "$used" --argjson missing "$missing" --argjson omitted "$omitted" --argjson truncated "$truncated" \
    '{format:"polylane-context-v1", query:$query, byte_count:$byte_count, content_checksum:$checksum, used_sources:$used, missing_sources:$missing, omitted_sources:$omitted, truncated_sources:$truncated}' > "$MANIFEST_TMP"
}

cmd_refresh() {
  ROOT=$(canonical_root "$1")
  shift
  WORKER=""
  while [ $# -gt 0 ]; do
    [ "$1" = '--worker' ] && [ $# -ge 2 ] || usage
    WORKER="$2"; valid_worker "$WORKER" || die "unsafe worker id"
    shift 2
  done
  setup_tmp
  collect_sources
  while IFS="$(printf '\t')" read -r rel label recency file; do printf 'available\t%s\t%s\n' "$label" "$rel"; done < "$SOURCES"
  while IFS= read -r rel; do [ -n "$rel" ] && printf 'missing\t%s\n' "$rel"; done < "$MISSING"
  while IFS= read -r rel; do [ -n "$rel" ] && printf 'omitted\t%s\n' "$rel"; done < "$OMITTED"
}

setup_tmp() {
  TMPDIR_CONTEXT=$(mktemp -d "${TMPDIR:-/tmp}/polylane-context.XXXXXX") || exit 2
  trap 'rm -rf "$TMPDIR_CONTEXT"' EXIT HUP INT TERM
  SOURCES="$TMPDIR_CONTEXT/sources.tsv"; MISSING="$TMPDIR_CONTEXT/missing.txt"; OMITTED="$TMPDIR_CONTEXT/omitted.txt"
  CANDIDATES="$TMPDIR_CONTEXT/candidates.tsv"; MAX_BRIEF="$TMPDIR_CONTEXT/max-brief.md"; USED="$TMPDIR_CONTEXT/used.txt"; TRUNCATED="$TMPDIR_CONTEXT/truncated.txt"
  RECENT_LIST="$TMPDIR_CONTEXT/recent.tsv"; PENDING_INBOX="$TMPDIR_CONTEXT/pending-inbox.jsonl"
}

cmd_packet() {
  [ $# -ge 4 ] || usage
  ROOT=$(canonical_root "$1"); OUT_INPUT="$2"; BUDGET="$3"; QUERY="$4"; shift 4
  case "$BUDGET" in ''|*[!0-9]*|0) die "byte budget must be a positive integer" ;; esac
  GOAL=""; SUBGOAL=""; WORKER=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --goal) [ $# -ge 2 ] || usage; GOAL="$2"; shift 2 ;;
      --subgoal) [ $# -ge 2 ] || usage; SUBGOAL="$2"; shift 2 ;;
      --worker) [ $# -ge 2 ] || usage; WORKER="$2"; valid_worker "$WORKER" || die "unsafe worker id"; shift 2 ;;
      *) usage ;;
    esac
  done
  # Resolve the existing declared parent before making the final directory.  This
  # catches both traversal and /tmp -> /private/tmp symlink aliases on macOS.
  mkdir -p "$ROOT/.polylane/context-packets" || die "cannot create packet directory"
  OUT_PARENT=$(cd "$(dirname "$OUT_INPUT")" 2>/dev/null && pwd -P) || die "unsafe packet directory"
  OUT="$OUT_PARENT/$(basename "$OUT_INPUT")"
  BASE=$(cd "$ROOT/.polylane/context-packets" && pwd -P)
  case "$OUT" in "$BASE"/*) ;; *) die "unsafe packet directory" ;; esac
  mkdir -p "$OUT" || die "cannot create packet directory"
  OUT=$(cd "$OUT" 2>/dev/null && pwd -P) || die "unsafe packet directory"
  setup_tmp
  PACKET_TMP="$TMPDIR_CONTEXT/context.md"; MANIFEST_TMP="$TMPDIR_CONTEXT/manifest.json"
  collect_sources
  make_candidates
  render_packet
  write_manifest
  mv "$PACKET_TMP" "$OUT/context.md"
  mv "$MANIFEST_TMP" "$OUT/manifest.json"
  printf 'context: packet=%s bytes=%s checksum=%s\n' "$OUT/context.md" "$(bytes "$OUT/context.md")" "$(jq -r '.content_checksum' "$OUT/manifest.json")"
}

case "${1:-}" in
  refresh) shift; [ $# -ge 1 ] || usage; cmd_refresh "$@" ;;
  packet|query) shift; cmd_packet "$@" ;;
  *) usage ;;
esac
